create or replace function public.ineed_admin_start_experiment(next_name text default null, config_override jsonb default null)
returns uuid language plpgsql security definer set search_path='public','auth' as $$
declare uid uuid:=auth.uid(); previous public.ineed_experiments%rowtype; cfg jsonb; start_amount numeric(14,4); cfg_version text; new_id uuid; available numeric(14,4); exposure numeric(14,4);
begin
  if uid is null or not public.is_admin(uid) then raise exception 'Tylko administrator może rozpocząć eksperyment iNeed$.'; end if;
  select * into previous from public.ineed_experiments where status='ACTIVE' for update;
  if found then
    select coalesce((select bankroll_after from public.ineed_bankroll_ledger where experiment_id=previous.id order by created_at desc,id desc limit 1),0) into available;
    select coalesce(sum(stake),0) into exposure from public.ineed_shadow_bets where experiment_id=previous.id and status in ('SHADOW_PLACED','PENDING');
    if exposure>0 then raise exception 'Nie można rozpocząć nowego eksperymentu, gdy poprzedni ma otwarte zakłady.'; end if;
    update public.ineed_experiments set status='COMPLETED',ended_at=now(),final_bankroll=available where id=previous.id;
    cfg:=coalesce(config_override,previous.config);
  else cfg:=config_override; end if;
  if cfg is null then raise exception 'Brak konfiguracji iNeed$.'; end if;
  if coalesce(cfg->>'operator','')<>'superbet.pl' or coalesce(cfg->>'mode','')<>'SHADOW' then raise exception 'V1 obsługuje wyłącznie superbet.pl / SHADOW'; end if;
  start_amount:=(cfg->>'starting_bankroll')::numeric; cfg_version:=coalesce(cfg->>'version','ineed-v1');
  insert into public.ineed_experiments(name,operator,mode,currency,starting_bankroll,config,config_version,status,created_by)
  values(coalesce(nullif(trim(next_name),''),'ROAD TO 1,000,000 — TEST #'||(coalesce((select max(experiment_no) from public.ineed_experiments),0)+1)::text),'superbet.pl','SHADOW','PLN',start_amount,cfg,cfg_version,'ACTIVE',uid) returning id into new_id;
  insert into public.ineed_bankroll_ledger(experiment_id,entry_type,amount,source,source_key,bankroll_before,bankroll_after) values(new_id,'INITIAL_DEPOSIT',start_amount,'experiment_start','initial:'||new_id,0,start_amount);
  insert into public.ineed_runtime_health(experiment_id,status,detail) values(new_id,'NEVER_RUN','{}');
  return new_id;
end $$;

grant execute on function public.ineed_admin_start_experiment(text,jsonb) to authenticated;

create or replace function public.ineed_system_settle_bet(target_bet_id uuid, settlement_outcome text, settlement_payout numeric, settlement_detail jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path='public','auth' as $$
declare b public.ineed_shadow_bets%rowtype; available numeric(14,4); other_exposure numeric(14,4); credit numeric(14,4); after_available numeric(14,4); after_equity numeric(14,4); entry text;
begin
  settlement_outcome:=upper(trim(settlement_outcome)); if settlement_outcome not in ('WIN','LOSS','VOID','CANCELLED') then raise exception 'Invalid iNeed settlement outcome'; end if;
  select * into b from public.ineed_shadow_bets where id=target_bet_id for update; if not found then raise exception 'iNeed bet not found'; end if;
  if b.status in ('WIN','LOSS','VOID','CANCELLED','SETTLED') then return jsonb_build_object('status','IDEMPOTENT','bet_id',b.id,'outcome',b.status); end if;
  select coalesce((select bankroll_after from public.ineed_bankroll_ledger where experiment_id=b.experiment_id order by created_at desc,id desc limit 1),0) into available;
  credit:=case when settlement_outcome='WIN' then greatest(coalesce(settlement_payout,0),0) when settlement_outcome in ('VOID','CANCELLED') then b.stake else 0 end;
  entry:=case settlement_outcome when 'WIN' then 'BET_WIN' when 'LOSS' then 'BET_LOSS' when 'VOID' then 'BET_VOID' else 'BET_CANCELLED' end; after_available:=available+credit;
  insert into public.ineed_bankroll_ledger(experiment_id,entry_type,amount,source,source_key,bet_id,bankroll_before,bankroll_after)
  values(b.experiment_id,entry,credit,'ineed_settlement','settle:'||b.id,b.id,available,after_available) on conflict(experiment_id,source_key) do nothing;
  select coalesce(sum(stake),0) into other_exposure from public.ineed_shadow_bets where experiment_id=b.experiment_id and id<>b.id and status in ('SHADOW_PLACED','PENDING'); after_equity:=after_available+other_exposure;
  update public.ineed_shadow_bets set status=settlement_outcome,payout=credit,net_profit=credit-b.stake,bankroll_after=after_equity,settlement_snapshot=settlement_detail,settled_at=now() where id=b.id;
  update public.ineed_signals set status=settlement_outcome,updated_at=now() where id=b.signal_id;
  return jsonb_build_object('status','SETTLED','bet_id',b.id,'outcome',settlement_outcome,'bankroll_after',after_equity);
end $$;
revoke all on function public.ineed_system_settle_bet(uuid,text,numeric,jsonb) from public,anon,authenticated;
grant execute on function public.ineed_system_settle_bet(uuid,text,numeric,jsonb) to service_role;

