-- iNeed$ V1: durable SHADOW bankroll/value/risk ledger. Applied to production 2026-09-10.
create table if not exists public.ineed_experiments (
  id uuid primary key default gen_random_uuid(),
  experiment_no bigint generated by default as identity unique,
  name text not null, operator text not null, mode text not null, currency text not null default 'PLN',
  starting_bankroll numeric(14,4) not null, config jsonb not null, config_version text not null,
  status text not null default 'ACTIVE', started_at timestamptz not null default now(), ended_at timestamptz,
  final_bankroll numeric(14,4), created_by uuid, created_at timestamptz not null default now()
);
create unique index if not exists ineed_one_active_experiment on public.ineed_experiments((status)) where status='ACTIVE';

create table if not exists public.ineed_signals (
  id uuid primary key default gen_random_uuid(), experiment_id uuid not null references public.ineed_experiments(id) on delete cascade,
  fingerprint text not null, status text not null, reason_code text, match_id text not null, market text not null, selection text,
  odds numeric, odds_timestamp timestamptz, model_probability numeric, raw_implied_probability numeric, no_vig_probability numeric,
  break_even_probability numeric, fair_odds numeric, edge_probability_points numeric, expected_value_net numeric,
  estimated_bookmaker_margin numeric, confidence numeric, data_quality text, proposed_stake numeric, final_stake numeric,
  current_snapshot jsonb not null default '{}'::jsonb, first_seen_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  unique(experiment_id,fingerprint)
);
create table if not exists public.ineed_decision_snapshots (
  id uuid primary key default gen_random_uuid(), experiment_id uuid not null references public.ineed_experiments(id) on delete cascade,
  signal_id uuid not null references public.ineed_signals(id) on delete cascade, snapshot_hash text not null, evaluated_at timestamptz not null,
  odds numeric, odds_timestamp timestamptz, status text not null, reason_code text, snapshot jsonb not null, created_at timestamptz not null default now(),
  unique(signal_id,snapshot_hash)
);
create table if not exists public.ineed_signal_events (
  id uuid primary key default gen_random_uuid(), experiment_id uuid not null references public.ineed_experiments(id) on delete cascade,
  signal_id uuid not null references public.ineed_signals(id) on delete cascade, from_status text, to_status text not null, reason_code text,
  event_at timestamptz not null default now()
);
create table if not exists public.ineed_shadow_bets (
  id uuid primary key default gen_random_uuid(), experiment_id uuid not null references public.ineed_experiments(id) on delete cascade,
  signal_id uuid not null unique references public.ineed_signals(id) on delete cascade, match_id text not null, market text not null, selection text,
  status text not null default 'PENDING', stake numeric(14,4) not null, odds numeric not null, potential_payout numeric, payout numeric,
  net_profit numeric, bankroll_before numeric not null, bankroll_after numeric, placement_snapshot jsonb not null,
  settlement_snapshot jsonb, placed_at timestamptz not null default now(), settled_at timestamptz
);
create table if not exists public.ineed_bankroll_ledger (
  id uuid primary key default gen_random_uuid(), experiment_id uuid not null references public.ineed_experiments(id) on delete cascade,
  entry_type text not null, amount numeric(14,4) not null, source text not null, source_key text not null, bet_id uuid references public.ineed_shadow_bets(id),
  bankroll_before numeric(14,4) not null, bankroll_after numeric(14,4) not null, created_at timestamptz not null default now(),
  unique(experiment_id,source_key)
);
create table if not exists public.ineed_email_events (
  id uuid primary key default gen_random_uuid(), experiment_id uuid not null references public.ineed_experiments(id) on delete cascade,
  signal_id uuid not null references public.ineed_signals(id) on delete cascade, event_type text not null, revision integer not null default 1,
  status text not null default 'PENDING', payload jsonb not null, provider_message_id text, attempt_count integer not null default 0,
  last_error text, created_at timestamptz not null default now(), sent_at timestamptz,
  unique(signal_id,event_type,revision)
);
create table if not exists public.ineed_runtime_health (
  experiment_id uuid primary key references public.ineed_experiments(id) on delete cascade, status text not null default 'NEVER_RUN',
  last_sync_at timestamptz, detail jsonb not null default '{}'::jsonb, updated_at timestamptz not null default now()
);

create or replace function public.ineed_log_signal_status() returns trigger language plpgsql security definer set search_path='public' as $$
begin
  if tg_op='INSERT' or new.status is distinct from old.status or new.reason_code is distinct from old.reason_code then
    insert into public.ineed_signal_events(experiment_id,signal_id,from_status,to_status,reason_code)
    values(new.experiment_id,new.id,case when tg_op='INSERT' then null else old.status end,new.status,new.reason_code);
  end if;
  return new;
end $$;
drop trigger if exists ineed_signal_status_audit on public.ineed_signals;
create trigger ineed_signal_status_audit after insert or update of status,reason_code on public.ineed_signals for each row execute function public.ineed_log_signal_status();

